/** Strings that are intentionally left untranslated (codes, sample data). */
export const AR_SKIP = new Set([
  '%s | Site Name',
  '+966 5x xxx xxxx',
  'ABCD1234',
  'CUP-PP-003',
  'PO-2026-XXX',
  'SUMMER25',
  'Paper Cups',
  'KCC x Saudi Vision 2030',
  'KCC × رؤية السعودية 2030',
]);

/** Translate an English source string; falls back to the English itself. */
export function translateString(en: string, locale: 'en' | 'ar'): string {
  if (locale !== 'ar') return en;
  return AR_STRINGS[en] ?? en;
}
